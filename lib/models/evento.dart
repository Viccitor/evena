
class Evento {
  final String id;
  final String titulo;
  final String imagemUrl;
  final String dia;
  final String mes;
  final String hora;
  final String local;
  final String endereco;
  final String descricao;
  final String formato;

  Evento({
    required this.id,
    required this.titulo,
    required this.imagemUrl,
    required this.dia,
    required this.mes,
    required this.hora,
    required this.local,
    required this.endereco,
    required this.descricao,
    required this.formato,
  });
}